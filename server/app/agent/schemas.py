"""Pydantic v2 schemas for Agent Loop and LLM Tool Gateway (Module B5)."""

from datetime import datetime
from decimal import Decimal
from enum import Enum
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, ConfigDict, Field


class AgentRunStatus(str, Enum):
    """Execution status outcomes of the agent loop."""

    COMPLETED = "completed"
    CLARIFICATION_NEEDED = "clarification_needed"
    NO_MATCH = "no_match"
    BUDGET_EXHAUSTED = "budget_exhausted"
    CANCELLED = "cancelled"
    FAILED = "failed"


class RequestUnderstanding(BaseModel):
    """Structured understanding of user's shopping request."""

    original_request: str
    product_type: str
    category: Optional[str] = None
    brand_preference: Optional[str] = None
    explicit_requirements: List[str] = Field(default_factory=list)
    inferred_preferences: List[str] = Field(default_factory=list)
    exclusions: List[str] = Field(default_factory=list)
    price_preference: Optional[Decimal] = None
    quantity: int = Field(default=1, ge=1, le=50)
    retailer_preferences: List[str] = Field(default_factory=list)
    is_clarification_needed: bool = False
    clarification_reason: Optional[str] = None
    confidence_score: float = Field(default=1.0, ge=0.0, le=1.0)

    model_config = ConfigDict(extra="ignore")


class ResearchPlan(BaseModel):
    """Structured research plan generated by the agent."""

    research_objective: str
    search_queries: List[str] = Field(default_factory=list)
    constraints: Dict[str, Any] = Field(default_factory=dict)
    approved_tools: List[str] = Field(default_factory=list)
    max_steps: int = Field(default=4, ge=1, le=10)

    model_config = ConfigDict(extra="ignore")


class ToolCallRequest(BaseModel):
    """Invocation request for an approved research tool."""

    call_id: str = Field(default_factory=lambda: uuid.uuid4().hex[:12])
    tool_name: str
    arguments: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(extra="forbid")


class ToolExecutionResult(BaseModel):
    """Safe normalized execution result of a tool call."""

    call_id: str
    tool_name: str
    status: str  # "success", "rejected", "error", "timeout"
    result: Optional[Any] = None
    error: Optional[str] = None
    duration_ms: float = 0.0

    model_config = ConfigDict(extra="ignore")


class ResearchOffer(BaseModel):
    """Structured offer discovered for a product candidate."""

    offer_key: str
    domain: str
    price_amount: Decimal
    currency: str = "USD"
    availability: str = "InStock"  # "InStock", "OutOfStock", "PreOrder", "Unknown"
    condition: str = "new"
    buy_url: str
    observed_at: datetime = Field(default_factory=lambda: datetime.now())

    model_config = ConfigDict(extra="ignore")


class ResearchCandidate(BaseModel):
    """Structured candidate product gathered through research tools."""

    product_id: str
    title: str
    brand: Optional[str] = None
    category: Optional[str] = None
    description: Optional[str] = None
    image_url: Optional[str] = None
    attributes: Dict[str, Any] = Field(default_factory=dict)
    offers: List[ResearchOffer] = Field(default_factory=list)
    source_provenance: str = "channel3"
    is_verified: bool = True
    missing_attributes: List[str] = Field(default_factory=list)

    model_config = ConfigDict(extra="ignore")


class AgentRunResult(BaseModel):
    """Final structured result returned by the Agent Loop to B4 orchestrator."""

    request_id: uuid.UUID
    status: AgentRunStatus
    understanding: Optional[RequestUnderstanding] = None
    plan: Optional[ResearchPlan] = None
    candidates: List[ResearchCandidate] = Field(default_factory=list)
    recommended_product_id: Optional[str] = None
    recommended_offer_key: Optional[str] = None
    rationale: Optional[str] = None
    limitations: List[str] = Field(default_factory=list)
    missing_information: List[str] = Field(default_factory=list)
    total_iterations: int = 0
    total_tool_calls: int = 0
    duration_seconds: float = 0.0
    error_code: Optional[str] = None
    error_message: Optional[str] = None

    model_config = ConfigDict(extra="ignore")
